
# This demonstrates how Python can be used to automate simple activities such as calculating purchase costs.
# Create variables to store business and product details
business_name = "Kamau Traders"
product_name = "Laptop"
product_price = 55000   # price in Kenyan Shillings
quantity_purchased = 3

# Calculate the total purchase cost
total_cost = product_price * quantity_purchased

# Display all the business transaction details
print("Business Name:", business_name)
print("Product Name:", product_name)
print("Product Price:", product_price)
print("Quantity Purchased:", quantity_purchased)
print("Total Cost:", total_cost)
